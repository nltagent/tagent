"""
Разовый скрипт — задаёт меню команд рядом с полем ввода в Telegram
(кнопка "/"). Запускать вручную после деплоя или при изменении списка
команд, не на каждом старте контейнера.

Показывает только самые частые команды — Telegram неудобно отображает
длинные меню, а полный список команд всегда доступен через /help.

Запуск (с теми же переменными окружения, что и у бота):
    TELEGRAM_BOT_TOKEN=... python scripts/set_commands.py
"""
import os
import sys

sys.path.insert(0, os.path.join(os.path.dirname(__file__), "..", "src"))

from telegram.api import set_my_commands  # noqa: E402

# (имя_без_слэша, короткое описание) — Telegram даёт до 32 символов на
# имя и до 256 на описание; со всем этим тут большой запас.
COMMANDS = [
    ("help", "Полный список команд"),
    ("note", "Сохранить заметку"),
    ("notes", "Показать заметки"),
    ("remind", "Создать напоминание"),
    ("reminders", "Активные напоминания"),
    ("search", "Поиск в интернете"),
    ("dialogs", "Список диалогов"),
    ("newdialog", "Начать новый диалог"),
    ("models", "Бесплатные модели"),
    ("setmodel", "Переключить модель"),
    ("status", "Состояние сервера"),
    ("selftest", "Живая самопроверка"),
]

if __name__ == "__main__":
    result = set_my_commands(COMMANDS)
    print(result)
    if not result.get("ok"):
        sys.exit(1)
